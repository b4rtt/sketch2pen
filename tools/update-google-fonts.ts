// Regenerates src/data/google-fonts.ts from the public Google Fonts metadata.
// pen.dev renders every Google Fonts family by name, so these never need to be embedded or substituted.
const res = await fetch('https://fonts.google.com/metadata/fonts');
let raw = await res.text();
if (raw.startsWith(")]}'")) raw = raw.slice(4);
const families = (JSON.parse(raw).familyMetadataList as { family: string }[]).map((f) => f.family).sort((a, b) => a.localeCompare(b));
const body = `// Generated by tools/update-google-fonts.ts – do not edit by hand.\n// ${families.length} families available in pen.dev without embedding.\nexport const GOOGLE_FONT_FAMILIES: readonly string[] = ${JSON.stringify(families)};\n`;
await Bun.write(new URL('../src/data/google-fonts.ts', import.meta.url), body);
console.log(`${families.length} Google Fonts families written`);
